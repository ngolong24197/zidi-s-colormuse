"""Loading and rasterising the reusable SVG garment/mannequin assets.

The assets (generated by scripts/build_svg_assets.py) contain only <path>
elements using M/L/H/V/C/Q/Z commands, tagged with a ``class`` that names the
color role. The same parsed geometry produces SVG markup for the browser and a
Pillow raster for PNG export, so both stay pixel-consistent with no native
SVG library dependency (important on Streamlit Community Cloud).
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from PIL import Image, ImageDraw

from src.core.color_convert import hex_to_rgb, lightness, mix, normalize_hex

ROOT = Path(__file__).resolve().parents[2]
MANNEQUIN_DIR = ROOT / "assets" / "mannequins"
TEMPLATE_DIR = ROOT / "assets" / "clothing_templates"

FILL_CLASSES = {"fill", "shade", "accent", "metal", "sole", "dark", "skin", "hair"}
STROKE_CLASSES = {"line", "strap"}
METAL_HEX = "#C9A44C"
SOLE_HEX = "#F3EEE6"

_TOKEN = re.compile(r"[MmLlHhVvCcQqZz]|-?\d*\.?\d+(?:[eE][-+]?\d+)?")

Point = tuple[float, float]


@dataclass(frozen=True)
class SubPath:
    points: tuple[Point, ...]
    closed: bool


@dataclass(frozen=True)
class AssetPath:
    cls: str
    d: str
    subpaths: tuple[SubPath, ...]


@dataclass(frozen=True)
class Asset:
    name: str
    slot: str
    paths: tuple[AssetPath, ...]

    @property
    def bbox(self) -> tuple[float, float, float, float]:
        xs = [p[0] for ap in self.paths for sp in ap.subpaths for p in sp.points]
        ys = [p[1] for ap in self.paths for sp in ap.subpaths for p in sp.points]
        if not xs:
            return 0.0, 0.0, 1.0, 1.0
        return min(xs), min(ys), max(xs), max(ys)


# ---------------------------------------------------------------- parsing

def _cubic(p0: Point, p1: Point, p2: Point, p3: Point, steps: int) -> list[Point]:
    out = []
    for i in range(1, steps + 1):
        t = i / steps
        u = 1 - t
        out.append((
            u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0],
            u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1],
        ))
    return out


def parse_path(d: str, steps: int = 10) -> tuple[SubPath, ...]:
    """Flatten an SVG path (M/L/H/V/C/Q/Z, absolute or relative) into polylines."""
    tokens = _TOKEN.findall(d)
    subpaths: list[SubPath] = []
    pts: list[Point] = []
    cur: Point = (0.0, 0.0)
    start: Point = (0.0, 0.0)
    cmd = ""
    i = 0

    def num() -> float:
        nonlocal i
        v = float(tokens[i])
        i += 1
        return v

    def flush(closed: bool) -> None:
        nonlocal pts
        if len(pts) >= 2:
            subpaths.append(SubPath(tuple(pts), closed))
        pts = []

    while i < len(tokens):
        tok = tokens[i]
        if tok.isalpha():
            cmd = tok
            i += 1
            if cmd in "Zz":
                flush(True)
                cur = start
                continue
        elif not cmd:
            raise ValueError(f"Path data must start with a command: {d[:30]}")
        rel = cmd.islower()
        c = cmd.upper()
        ox, oy = cur if rel else (0.0, 0.0)
        if c == "M":
            flush(False)
            cur = (ox + num(), oy + num())
            start = cur
            pts = [cur]
            cmd = "l" if rel else "L"  # implicit lineto after moveto
        elif c == "L":
            cur = (ox + num(), oy + num())
            pts.append(cur)
        elif c == "H":
            cur = ((cur[0] if rel else 0.0) + num(), cur[1])
            pts.append(cur)
        elif c == "V":
            cur = (cur[0], (cur[1] if rel else 0.0) + num())
            pts.append(cur)
        elif c == "C":
            p1 = (ox + num(), oy + num())
            p2 = (ox + num(), oy + num())
            p3 = (ox + num(), oy + num())
            pts.extend(_cubic(cur, p1, p2, p3, steps))
            cur = p3
        elif c == "Q":
            q = (ox + num(), oy + num())
            p3 = (ox + num(), oy + num())
            p1 = (cur[0] + 2 / 3 * (q[0] - cur[0]), cur[1] + 2 / 3 * (q[1] - cur[1]))
            p2 = (p3[0] + 2 / 3 * (q[0] - p3[0]), p3[1] + 2 / 3 * (q[1] - p3[1]))
            pts.extend(_cubic(cur, p1, p2, p3, steps))
            cur = p3
        else:
            raise ValueError(f"Unsupported path command: {cmd}")
    flush(False)
    return tuple(subpaths)


def _parse_svg(path: Path) -> Asset:
    root = ET.parse(path).getroot()
    paths = []
    for el in root.iter():
        if el.tag.endswith("path"):
            cls = el.get("class", "fill")
            d = el.get("d", "")
            paths.append(AssetPath(cls, d, parse_path(d)))
    return Asset(root.get("data-name", path.stem), root.get("data-slot", ""), tuple(paths))


@lru_cache(maxsize=64)
def load_template(variant: str) -> Asset:
    p = TEMPLATE_DIR / f"{variant}.svg"
    if not p.exists():
        raise FileNotFoundError(f"No garment template for variant {variant!r}")
    return _parse_svg(p)


@lru_cache(maxsize=64)
def load_mannequin_layer(name: str) -> Asset:
    return _parse_svg(MANNEQUIN_DIR / f"{name}.svg")


def available_variants() -> list[str]:
    return sorted(p.stem for p in TEMPLATE_DIR.glob("*.svg"))


# ---------------------------------------------------------------- colors

def role_colors(main_hex: str, secondary_hex: str | None = None) -> dict[str, str]:
    """Color for each path class, derived from the garment's main color."""
    main = normalize_hex(main_hex)
    dark = lightness(main) < 28
    shade = mix(main, "#FFFFFF", 0.14) if dark else mix(main, "#1A1414", 0.16)
    line = mix(main, "#FFFFFF", 0.32) if dark else mix(main, "#1A1414", 0.38)
    if secondary_hex:
        accent = normalize_hex(secondary_hex)
    else:
        accent = mix(main, "#F8F4EF", 0.55) if lightness(main) < 60 else mix(main, "#302B2B", 0.5)
    return {
        "fill": main, "shade": shade, "line": line, "strap": shade, "accent": accent,
        "metal": METAL_HEX, "sole": SOLE_HEX, "dark": "#302B2B", "outline": line,
    }


def body_colors(skin_hex: str, hair_hex: str) -> dict[str, str]:
    skin, hair = normalize_hex(skin_hex), normalize_hex(hair_hex)
    return {
        "skin": skin, "hair": hair,
        "skin_outline": mix(skin, "#4A2E25", 0.35),
        "hair_outline": mix(hair, "#000000", 0.3) if lightness(hair) > 25 else mix(hair, "#FFFFFF", 0.18),
    }


# ---------------------------------------------------------------- raster drawing

@dataclass(frozen=True)
class Transform:
    scale: float
    dx: float
    dy: float

    def apply(self, pts: tuple[Point, ...]) -> list[Point]:
        return [(x * self.scale + self.dx, y * self.scale + self.dy) for x, y in pts]


def draw_asset(
    canvas: Image.Image,
    asset: Asset,
    tf: Transform,
    colors: dict[str, str],
    pattern_tile: Image.Image | None = None,
    outline_key: str = "outline",
    stroke_scale: float = 1.0,
) -> None:
    """Rasterise an asset onto an RGBA canvas (draw at 2-3x and downsample for AA)."""
    draw = ImageDraw.Draw(canvas)
    outline = colors.get(outline_key, colors.get("line", "#302B2B"))
    w_outline = max(1, int(round(1.3 * tf.scale * stroke_scale)))
    for ap in asset.paths:
        if ap.cls in STROKE_CLASSES:
            width = max(1, int(round((4.5 if ap.cls == "strap" else 1.4) * tf.scale * stroke_scale)))
            col = colors.get(ap.cls, outline)
            for sp in ap.subpaths:
                pts = tf.apply(sp.points + ((sp.points[0],) if sp.closed else ()))
                draw.line(pts, fill=hex_to_rgb(col), width=width, joint="curve")
            continue
        col = colors.get(ap.cls, colors.get("fill", "#999999"))
        for sp in ap.subpaths:
            pts = tf.apply(sp.points)
            if len(pts) < 3:
                continue
            if ap.cls == "fill" and pattern_tile is not None:
                x0 = max(0, int(min(p[0] for p in pts)))
                y0 = max(0, int(min(p[1] for p in pts)))
                x1 = min(canvas.width, int(max(p[0] for p in pts)) + 2)
                y1 = min(canvas.height, int(max(p[1] for p in pts)) + 2)
                if x1 > x0 and y1 > y0:
                    mask = Image.new("L", (x1 - x0, y1 - y0), 0)
                    ImageDraw.Draw(mask).polygon([(x - x0, y - y0) for x, y in pts], fill=255)
                    canvas.paste(tile_region(pattern_tile, (x0, y0, x1, y1)), (x0, y0), mask)
            else:
                draw.polygon(pts, fill=hex_to_rgb(col))
            draw.line(pts + [pts[0]], fill=hex_to_rgb(outline), width=w_outline, joint="curve")


def tile_region(tile: Image.Image, box: tuple[int, int, int, int]) -> Image.Image:
    """The canvas-aligned tiling of ``tile`` covering ``box`` (x0, y0, x1, y1)."""
    x0, y0, x1, y1 = box
    tw, th = tile.size
    sx, sy = (x0 // tw) * tw, (y0 // th) * th
    big = Image.new("RGB", (x1 - sx + tw, y1 - sy + th))
    for y in range(0, big.height, th):
        for x in range(0, big.width, tw):
            big.paste(tile, (x, y))
    return big.crop((x0 - sx, y0 - sy, x0 - sx + (x1 - x0), y0 - sy + (y1 - y0)))


# ---------------------------------------------------------------- SVG markup

def svg_paths(asset: Asset, colors: dict[str, str], pattern_id: str | None = None,
              outline_key: str = "outline", stroke_scale: float = 1.0) -> str:
    """Markup for an asset's paths with resolved colors."""
    outline = colors.get(outline_key, colors.get("line", "#302B2B"))
    parts = []
    for ap in asset.paths:
        if ap.cls in STROKE_CLASSES:
            width = (4.5 if ap.cls == "strap" else 1.4) * stroke_scale
            parts.append(
                f'<path d="{ap.d}" fill="none" stroke="{colors.get(ap.cls, outline)}" '
                f'stroke-width="{width:.2f}" stroke-linecap="round" stroke-linejoin="round"/>'
            )
            continue
        fill = colors.get(ap.cls, colors.get("fill", "#999999"))
        if ap.cls == "fill" and pattern_id:
            fill = f"url(#{pattern_id})"
        parts.append(
            f'<path d="{ap.d}" fill="{fill}" stroke="{outline}" stroke-width="{1.3 * stroke_scale:.2f}" '
            f'stroke-linejoin="round"/>'
        )
    return "\n".join(parts)
